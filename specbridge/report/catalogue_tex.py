"""THE SUPPLEMENT'S CATALOGUES (2026-10-25): every library choice counted in Table S2 and every accepted request set, in full, so
a reader can check each one by hand. Generated from the same files as the paper's numbers; no model calls.
    python -m specbridge.report.catalogue_tex   -> paper/tex/cat_library.tex, paper/tex/cat_sets.tex"""
import collections, json, re
from specbridge.report import accepted as AC
from specbridge.comm.transfer import combined as CB
from specbridge.comm.transfer.review_table import differ

OUT = "paper/tex/"
TYPE = {"aggregation_level": "Aggregation level", "calculation": "Calculation", "comparison_quantifier": "Quantifier",
        "condition_linkage": "Condition linkage", "counting_unit": "Counting unit", "missing_values": "Missing values",
        "negated_membership_scope": "Negation", "population_scope": "Population scope", "referent_column": "Referent column",
        "relationship_role": "Relationship role", "strict_cutoff": "Strict cutoff", "ties_and_selection": "Ties and selection",
        "time_scope": "Time scope", "value_matching": "Value matching",
        "tie": "Ties and selection", "value_representation": "Strict cutoff"}          # the request sets' names for the same types
UNI = {"\u2212": "$-$", "\u00f7": "$\\div$", "\u2013": "--", "\u2014": "---", "\u2192": "$\\rightarrow$", "\u00d7": "$\\times$",
       "\u00a0": "~", "\u2264": "$\\leq$", "\u2265": "$\\geq$", "\u201c": "``", "\u201d": "''", "\u2018": "`", "\u2019": "'"}


def esc(s):
    """Plain text to LaTeX: special characters escaped, `code` set in typewriter type with break points after _ . and (."""
    def plain(t):
        t = t.replace("\\", "\\textbackslash{}")
        for a, b in (("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"),
                     ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}"), ("<", "\\textless{}"), (">", "\\textgreater{}")):
            t = t.replace(a, b)
        t = t.replace("\\textbackslash\\{\\}", "\\textbackslash{}")
        return "".join(UNI.get(c, c) for c in t)
    out = []
    for i, part in enumerate(re.split(r"`([^`]*)`", (s or "").strip())):
        if i % 2: out.append("\\texttt{%s}" % plain(part).replace("\\_", "\\_\\allowbreak{}").replace(".", ".\\allowbreak{}"))
        else: out.append(plain(part))
    return re.sub(r"\s*\n\s*", " ", "".join(out))


def _strict_only(a, b):                                     # as specbridge.report.exhibit_data.tab2 splits value representation
    n = lambda q: re.sub(r"\s+", " ", re.sub(r"(\S+) BETWEEN (\S+) AND (\S+)", r"\1 > \2 AND \1 < \3", q, flags=re.I)).replace(">=", ">").replace("<=", "<").strip().rstrip(";")
    return a != b and n(a) == n(b)


def library():
    E = [json.loads(l) for l in open("library/examples.jsonl")]
    rows = []
    for e in E:                                                 # the choices of meaning from failures that Table S2 counts
        if e["type"] == "output_form" or "decision site" in str(e.get("provenance", {}).get("from")): continue
        R = {r.get("id"): r for r in e.get("readings", [])}; t = e["type"]
        if t == "value_representation":
            t = "strict_cutoff" if R.get("A") and R.get("B") and _strict_only(R["A"].get("sql", ""), R["B"].get("sql", "")) else "value_matching"
        rows.append((TYPE[t], not e["raise"], e["source"]["benchmark"] != "BIRD dev", e["id"], e, R))
    rows.sort(key=lambda r: r[:4])
    n = collections.Counter(not r[1] for r in rows)
    L = ["% generated by python -m specbridge.report.catalogue_tex; do not edit",
         "\\begin{xltabular}{\\textwidth}{@{}>{\\raggedright\\arraybackslash}p{1.75cm}>{\\hsize=1.25\\hsize\\raggedright\\arraybackslash}X"
         ">{\\hsize=0.95\\hsize\\raggedright\\arraybackslash}X>{\\hsize=0.9\\hsize\\raggedright\\arraybackslash}X>{\\hsize=0.9\\hsize\\raggedright\\arraybackslash}X@{}}",
         "\\caption{Every choice of meaning found in a benchmark failure (%d: %d open, %d settled by the wording), by type, as counted in "
         "Table~\\ref{tab:librarydetail}. Question: the benchmark question with its evidence. The two readings are written as the "
         "reviewers recorded them; each also has an SQL query in the package (\\texttt{library/examples.jsonl}, by record id).}"
         % (len(rows), n[True], n[False]),
         "\\label{tab:catlibrary}\\\\", "\\toprule", "Source & Question & The choice & Reading A & Reading B\\\\", "\\midrule", "\\endfirsthead",
         "\\toprule", "Source & Question & The choice & Reading A & Reading B\\\\", "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"]
    last = None
    for ty, settled, _sp, rid, e, R in rows:
        if (ty, settled) != last:
            if last is not None: L.append("\\midrule")
            L.append("\\multicolumn{5}{@{}l}{\\textbf{%s}, %s}\\\\[1pt]" % (ty, "settled by the wording" if settled else "open"))
            last = (ty, settled)
        s = e["source"]
        src = "%s\\newline\\texttt{%s}\\newline{\\color{gray}%s}" % (s["benchmark"].replace(" dev", ""), esc(s["database"]).replace("\\_", "\\_\\allowbreak{}"),
                                                     esc(rid.rsplit(":", 1)[0]).replace("\\_", "\\_\\allowbreak{}").replace(":", ":\\allowbreak{}"))
        L.append("%s & %s & %s & %s & %s\\\\[2pt]" % (src, esc(e["question"]), esc(e["decision"]),
                                                    esc((R.get("A") or {}).get("reading")), esc((R.get("B") or {}).get("reading"))))
    L.append("\\end{xltabular}")
    open(OUT + "cat_library.tex", "w").write("\n".join(L) + "\n")
    return len(rows)


def sets():
    C, per = AC.per_set()
    V = json.load(open("human_supervision/verdicts.json")); W = json.load(open(CB.D + "/written.json"))
    keys = [k for k in C if V[k.split("-")[-1]]["verdict"] == "yes"]
    code = lambda x: "B" if x["covers"] else ("N" if x["single_both"] and x["names"] else ("S" if x["single_both"] else "--"))
    order = sorted(keys, key=lambda k: (TYPE[C[k]["type"]], k not in set(CB.part_cases(0)), C[k]["database"], k.split("-")[-1]))
    n_f = sum(k not in set(CB.part_cases(0)) for k in keys)
    L = ["% generated by python -m specbridge.report.catalogue_tex; do not edit",
         "\\begin{xltabular}{\\textwidth}{@{}>{\\raggedright\\arraybackslash}p{1.5cm}>{\\hsize=1.45\\hsize\\raggedright\\arraybackslash}X"
         ">{\\hsize=0.95\\hsize\\raggedright\\arraybackslash}X>{\\raggedright\\arraybackslash}p{1.9cm}>{\\hsize=0.6\\hsize\\raggedright\\arraybackslash}X"
         ">{\\centering\\arraybackslash}p{1.05cm}@{}}",
         "\\caption{Every accepted request set (%d, %d of them with a filter condition), by choice type. Open request: the text the models "
         "were given (each set also has one specific request per reading). Results: how the two reference answers differ on the "
         "database. Review: the author's reason for accepting the set. Models (Haiku, Sonnet, GPT-Sol, GPT-Luna), for the open request "
         "in one call with explanation: B both readings returned; N one reading, the choice named; S one reading, silent, although "
         "the model computes both when asked; -- one reading, and the model does not compute both. Full sets with SQL, schema and "
         "grading: \\texttt{benchmark/request\\_sets.jsonl}, by set id.}" % (len(keys), n_f),
         "\\label{tab:catsets}\\\\", "\\toprule", "Set & Open request & Readings & Results & Review & Models\\\\", "\\midrule", "\\endfirsthead",
         "\\toprule", "Set & Open request & Readings & Results & Review & Models\\\\", "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"]
    last = None
    for k in order:
        c = C[k]; w = W[k]; ty = TYPE[c["type"]]; filt = k not in set(CB.part_cases(0))
        if (ty, filt) != last:
            if last is not None: L.append("\\midrule")
            L.append("\\multicolumn{6}{@{}l}{\\textbf{%s}%s}\\\\[1pt]" % (ty, ", choice in a filter condition" if filt else ""))
            last = (ty, filt)
        sid = k.split("-")[-1]
        models = "\\texttt{%s}" % "\\,".join(code(per[(m, k)]).replace("--", "-") for m in AC.MODELS)
        L.append("\\texttt{%s}\\newline\\texttt{%s} & %s & \\textbf{A:} %s\\newline \\textbf{B:} %s & %s & %s & %s\\\\[2pt]" % (
            sid, esc(c["database"]).replace("\\_", "\\_\\allowbreak{}"), esc(w["open"]), esc(w["reading_A"]), esc(w["reading_B"]),
            esc(re.sub(r"\b1 rows", "1 row", differ(c["answer_A"], c["answer_B"] or []))), esc(V[sid].get("note", "")), models))
    L.append("\\end{xltabular}")
    open(OUT + "cat_sets.tex", "w").write("\n".join(L) + "\n")
    return len(keys)


if __name__ == "__main__":
    print("library choices:", library(), "| accepted request sets:", sets())
