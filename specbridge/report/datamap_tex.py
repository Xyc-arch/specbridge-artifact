"""DATA MAP FOR THE SUPPLEMENT (2026-10-25): which data each experiment uses, how the request sets are built from the sources,
and every sample size. Writes paper/tex/figures/tikz/datamap.tex (built by paper/tex/Makefile into figures/diag_datamap.pdf).
    python -m specbridge.report.datamap_tex
Every count is read through the number ledger (specbridge.report.numbers), from the same entry that checks the paper's text,
so the map cannot disagree with the paper. The library counts come from specbridge.report.catalogue_tex.lib_rows."""
from specbridge.report import numbers as N, catalogue_tex as C

OUT = "paper/tex/figures/tikz/datamap.tex"
REWRITE_PER_MODEL = 120          # design parameter: first 120 readings per model in the pre-shuffled order (out/rewrite/GATE.md)


def V(anchor, i=0):
    """The value of placeholder i of the one ledger entry whose anchor contains `anchor`."""
    E = [e for e in N.ledger() if anchor in e["anchor"]]
    assert len(E) == 1, (anchor, len(E))
    sp = E[0]["specs"][i]; assert sp.kind == "data", (anchor, i, sp.kind)
    v = sp.fn(); return int(round(float(v[0] if isinstance(v, list) else v)))


def n(v): return "{:,}".format(v)


def values():
    L = C.lib_rows()
    S = dict(tried=V("Its rules find usable queries on", 1), usable=V("Its rules find usable queries on", 0),
             dbs=V("Request sets use # databases"), delivered=V("it delivers # of # requested", 1), requested=V("it delivers # of # requested", 2),
             tasks=V("Exact description versus natural request on #"), swap=V("second version of # random tasks"),
             plan=V("tasks drawn at random across choice types"), attempts=V("(# attempts). The labels"),
             configs=len(N.P("fig1_coverage")["ablation"]),
             main=N.P("tab3_generation")["funnel"]["frozen"], filt=sum(N.FIL()["verdicts"].values()),
             checked=V("in each of the # sets that pass all checks"), author=V("The author keeps # sets", 0), final=V("The author keeps # sets", 1),
             filt_acc=N.FIL()["accepted"],
             lib=len(L), lib_open=sum(1 for r in L if r["raise"]), lib_types=len({r["display"] for r in L}), lib_dbs=len({r["source"]["database"] for r in L}),
             bird_mine=V("questions on five databases to mine the library", 0), bird_held=V("questions on five databases to mine the library", 1),
             spider_mine=V("& # questions to mine the library", 0), spider_held=V("& # questions to mine the library", 1),
             amb_dev=V("We developed the method on # AMBROSIA"), amb_test=V("The final test uses # new test questions", 0),
             amb_ambig=V("The final test uses # new test questions", 1), amb_clear=V("The final test uses # new test questions", 2),
             conv=V("In # tie and counting sets"), samp=V("in a random draw of #, five SQL-only", 0), samp_draw=V("in a random draw of #, five SQL-only", 2),
             impact=V("Of # such questions", 0), changed=V("Of # such questions", 1), rescore=V("We ask the four models # BIRD"),
             meth=V("sets that lie in a random draw of #", 0), meth_draw=V("sets that lie in a random draw of #", 2),
             rw=V("The run covers # readings per model", 1), bird_rw=V("comparison on # BIRD development questions"))
    S["main_acc"] = S["final"] - S["filt_acc"]; S["lib_settled"] = S["lib"] - S["lib_open"]
    assert S["main"] + S["filt"] == S["checked"], S
    return S


def tex(S):
    s = {k: n(v) for k, v in S.items()}
    H = {}                                                                 # minimum height per row, so the boxes of a row align
    box = lambda name, x, y, w, head, body: (
        "\\node[bx] (%s) at (%.2f,0 |- %s) {\\parbox[t][%.2fcm][t]{%.2fcm}{\\nohyph\\raggedright\\hd{%s}%s}};" % (name, x, y, H[y], w, head, body))
    T = [r"% generated by python -m specbridge.report.datamap_tex; do not edit",
         r"% Data map: sources (top), data built from them (middle), experiments with their sample sizes (bottom).",
         r"\input{style}", r"\begin{document}",
         r"\begin{tikzpicture}[x=1cm, y=1cm, font=\scriptsize, >=Stealth, line width=0.5pt,",
         r"  bx/.style={execute at begin node=\nohyph, draw=sbline, rounded corners=1pt, inner sep=2.6pt, align=left, anchor=north west},",
         r"  ex/.style={bx, fill=sbfill},",
         r"  band/.style={font=\scriptsize\bfseries, anchor=north west, inner sep=0pt},",
         r"  arr/.style={->, draw=sbline}]",
         r"\newcommand{\hd}[1]{\textbf{\footnotesize #1}\\[1pt]}",
         r"\coordinate (r1) at (0,0);", r"\node[band] at (0,0.42) {Sources};"]
    H.update(r1=2.2, r2=1.25, r3=2.0)
    W, G = 4.1, 0.32; X = [i * (W + G) for i in range(4)]
    # ---- sources
    T += [box("dbs", X[0], "r1", W, "Databases",
              "Spider, BIRD development, LiveSQLBench: %(tried)s tried, %(usable)s usable for the generator.\\\\%(dbs)s evaluation databases, four per source" % s),
          box("qs", X[2], "r1", W, "BIRD and Spider questions",
              "BIRD development: %(bird_mine)s questions on five databases to mine choices, %(bird_held)s held out.\\\\"
              "Spider development: %(spider_mine)s to mine, %(spider_held)s held out.\\\\References of all silent questions, training and development" % s),
          box("amb", X[3], "r1", W, "AMBROSIA",
              "%(amb_dev)s development questions; %(amb_test)s new test questions per model (%(amb_ambig)s ambiguous, %(amb_clear)s unambiguous)" % s),
          box("mod", X[1], "r1", W, "Models",
              "Evaluated: Haiku, Sonnet, GPT-Sol, GPT-Luna.\\\\Opus writes and reviews request sets with Sonnet, reviews Sonnet's natural requests, and judges explanations; it is not evaluated")]
    # ---- built data
    y2 = "r2"
    T += [r"\coordinate (r2) at ($(0,0 |- current bounding box.south)+(0,-0.62)$);", r"\node[band] at ($(r2)+(0,0.42)$) {Built from them};",
          box("gen", X[0], y2, W, "Generated tasks",
              "on the %(dbs)s evaluation databases: %(delivered)s of %(requested)s queries delivered; %(tasks)s tasks with a natural request" % s),
          box("rs", X[1], y2, W, "Request sets",
              "main run %(main)s and filter run %(filt)s pass all checks (%(checked)s); the author keeps %(author)s; the 1\\%% rule leaves \\textbf{%(final)s} (%(main_acc)s without, %(filt_acc)s with a filter)" % s),
          box("lib", X[2], y2, W, "Choice library",
              "%(lib)s choices (%(lib_open)s open, %(lib_settled)s settled) in %(lib_types)s types, from benchmark failures on %(lib_dbs)s databases" % s)]
    # ---- experiments
    y3 = "r3"
    T += [r"\coordinate (r3) at ($(0,0 |- current bounding box.south)+(0,-0.62)$);", r"\node[band] at ($(r3)+(0,0.42)$) {Experiments and sample sizes};",
          box("e1", X[0], y3, W, "Generator (Sec.~4.2)",
              "coverage on %(tried)s databases; each rule removed, %(configs)s configurations $\\times$ %(attempts)s attempts; exact description vs.\\ natural request on %(tasks)s tasks; "
              "second writer on %(swap)s random tasks; plan vs.\\ direct writing on %(plan)s tasks" % s),
          box("e2", X[1], y3, W, "Do models report the choice? (Sec.~5)",
              "%(final)s sets $\\times$ 4 models, three requests each; conventions on %(conv)s tie and counting sets; five samples on %(samp)s sets (random draw of %(samp_draw)s); "
              "filter sets: %(filt_acc)s (App.~C)" % s),
          box("e3", X[2], y3, W, "Can benchmarks see it? (Sec.~6)",
              "held-out %(bird_held)s BIRD and %(spider_held)s Spider questions; causes of the mining failures; conventions of silent references; "
              "%(impact)s silent BIRD questions, %(changed)s change; %(rescore)s BIRD questions rescored" % s),
          box("e4", X[3], y3, W, "Two design rules (Sec.~7)",
              "AMBROSIA test, Sonnet and GPT-Sol; %(meth)s request sets (random draw of %(meth_draw)s); edit vs.\\ rewrite on %(rw)s readings "
              "(%(rwpm)s per model drawn); %(bird_rw)s BIRD questions" % dict(s, rwpm=n(REWRITE_PER_MODEL)))]
    T = [t.replace("\\node[bx] (e", "\\node[ex] (e") for t in T]
    T += [r"% ---- arrows: what is built from what, and what each experiment uses",
          r"\draw[arr] (dbs.south) -- (gen.north);",
          r"\draw[arr] (qs.south) -- (lib.north);",
          r"\draw[arr] (gen.east) -- (rs.west);",
          r"\draw[arr] (lib.west) -- (rs.east);",
          r"\draw[arr] (gen.south) -- (e1.north);",
          r"\draw[arr] (rs.south) -- (e2.north);",
          r"\draw[arr] (lib.south) -- (e3.north);",
          r"\draw[arr] (amb.south) -- (e4.north);",
          r"\draw[arr] (rs.south east) .. controls +(1.2,-0.35) and +(-1.6,0.45) .. (e4.north west);",
          r"\end{tikzpicture}", r"\end{document}"]
    return "\n".join(T) + "\n"


if __name__ == "__main__":
    S = values(); open(OUT, "w").write(tex(S)); print("data map:", OUT, "| request sets %(checked)d -> %(author)d -> %(final)d" % S)
